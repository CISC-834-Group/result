#!/usr/bin/env python3
"""
Flag AI-attributed commits from an SQLite database containing processed git commits.

Tiers (kept separate so you can run strict-only analyses):
  direct_trailer : message names an AI tool (Co-authored-by trailer, "Generated with ...", robot emoji)
  propagated     : author has a direct_trailer commit earlier in the window; all of their
                   later commits (or the whole window, see --propagate) are flagged
  none           : not flagged

Usage:
  python flag_ai_commits.py --db repo.db --since 2025-11-01 --out ai_flags.csv
  # false-positive baseline on a pre-AI period:
  python flag_ai_commits.py --db repo.db --since 2019-01-01 --until 2020-12-31 --out baseline.csv
"""

import argparse
import csv
import re
import sqlite3
from collections import Counter, defaultdict
from datetime import datetime

AI_NAMES = r"(claude|anthropic|copilot|chatgpt|openai|gpt-?\d|codex|cursor|gemini|aider|devin|windsurf|codeium|tabnine)"

AI_NAMES_RE = re.compile(AI_NAMES, re.IGNORECASE | re.MULTILINE)
# Co-authored-by trailer whose name or email mentions an AI tool
COAUTHOR_RE = re.compile(
    rf"^\s*co-authored-by:.*{AI_NAMES}.*$", re.IGNORECASE | re.MULTILINE
)
# "Generated with Claude Code", "Generated by ChatGPT", etc.
GENERATED_RE = re.compile(
    rf"(generated|created|written|authored)\s+(with|by|using)\b.{{0,40}}{AI_NAMES}",
    re.IGNORECASE,
)
ROBOT_RE = re.compile("\U0001f916")  # robot emoji


def read_commits(db_path, since, until):
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()

    query = """
        SELECT hash, author_email, author_date, message
        FROM commits
        WHERE is_automated = 0 and is_merge = 0 AND author_date >= ?
    """
    params = [since]

    if until:
        # If until is just a date (YYYY-MM-DD), expand it to include the end of that day
        until_val = until + " 23:59:59" if len(until) == 10 else until
        query += " AND author_date <= ?"
        params.append(until_val)

    cursor.execute(query, params)
    rows = cursor.fetchall()
    conn.close()

    commits = []
    for sha, email, date_str, msg in rows:
        if not email or not date_str or not msg:
            continue

        # Parse ISO 8601 date string safely
        try:
            dt = datetime.fromisoformat(date_str.replace(" ", "T").replace("Z", "+00:00"))
        except ValueError:
            dt = datetime.strptime(date_str, "%Y-%m-%d %H:%M:%S")

        commits.append(
            {
                "sha": sha.strip(),
                "author": email.strip().lower(),
                "date": dt,
                "msg": msg,
            }
        )

    commits.sort(key=lambda c: c["date"])
    return commits


def direct_flags(msg):
    flags = []
    if (
        COAUTHOR_RE.search(msg)
        or GENERATED_RE.search(msg)
        or ROBOT_RE.search(msg)
        or AI_NAMES_RE.search(msg)
    ):
        flags.append("direct_trailer")
    return flags


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", required=True, help="Path to the SQLite database file")
    ap.add_argument("--since", default="2025-11-01")
    ap.add_argument("--until", default=None)
    ap.add_argument(
        "--propagate",
        choices=["from_first_flag", "whole_window"],
        default="from_first_flag",
        help="flag an author's commits after their first direct flag, or all of them in the window",
    )
    ap.add_argument("--out", default="ai_flags.csv")
    args = ap.parse_args()

    commits = read_commits(args.db, args.since, args.until)

    # Pass 1: direct flags and each author's earliest direct flag
    first_flag = {}
    for c in commits:
        c["flags"] = direct_flags(c["msg"])
        if c["flags"] and c["author"] not in first_flag:
            first_flag[c["author"]] = (c["date"], c["flags"])

    # Pass 2: assign tier
    for c in commits:
        if "direct_trailer" in c["flags"]:
            c["tier"] = "direct_trailer"
        elif c["author"] in first_flag and (
            args.propagate == "whole_window" or c["date"] >= first_flag[c["author"]][0]
        ):
            c["tier"] = f"propagated{first_flag[c['author']][1]}"
        else:
            c["tier"] = "none"

    with open(args.out, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["sha", "author", "date", "tier", "word_count"])
        for c in commits:
            w.writerow(
                [
                    c["sha"],
                    c["author"],
                    c["date"].isoformat(),
                    c["tier"],
                    len(c["msg"].split()),
                ]
            )

    # Summary
    tiers = Counter(c["tier"] for c in commits)
    print(f"commits scanned: {len(commits)}")
    for t in tiers:
        print(f"  {t:15s} {tiers[t]}")
    print(f"authors with a direct flag: {len(first_flag)}")
    by_month = defaultdict(Counter)
    for c in commits:
        by_month[c["date"].strftime("%Y-%m")][c["tier"] != "none"] += 1
    print("flagged per month (flagged / total):")
    for m in sorted(by_month):
        fl, nf = by_month[m][True], by_month[m][False]
        print(f"  {m}: {fl}/{fl + nf}")


if __name__ == "__main__":
    main()
